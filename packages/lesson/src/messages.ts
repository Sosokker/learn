export const lessonMessages: Record<LessonLang, Record<LessonMessageKey, string>> = { en, th }

export type Translate = (key: LessonMessageKey, params?: Readonly<Record<string, string | number>>) => string

export const makeTranslate = (lang: LessonLang): Translate => {
  const dict = lessonMessages[lang]
  return (key, params) =>
    dict[key].replace(/\{(\w+)\}/g, (match, name: string) => {
      const value = params?.[name]
      return value === undefined ? match : String(value)
    })
}

export const roleKey = (role: Role): LessonMessageKey => `role.${role}`
